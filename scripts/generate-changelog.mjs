#!/usr/bin/env node
// Generates CHANGELOG.md and docs/frontend/src/data/changelog.ts from git history.
//
// Incremental: reads the last-processed commit SHA from .changelog-state.json,
// only walks commits after it, and prepends new entries. Run with no state
// file (or delete it) to regenerate from the full history.
//
// Usage: node scripts/generate-changelog.mjs

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const STATE_PATH = path.join(ROOT, '.changelog-state.json');
const CHANGELOG_MD_PATH = path.join(ROOT, 'CHANGELOG.md');
const CHANGELOG_TS_PATH = path.join(ROOT, 'docs/frontend/src/data/changelog.ts');

const SECTION_ORDER = ['Added', 'Changed', 'Fixed'];
const CONVENTIONAL_TYPES = new Set([
  'feat', 'fix', 'docs', 'style', 'refactor', 'perf', 'test', 'build', 'ci', 'chore', 'revert',
]);

function typeToSection(type) {
  if (type === 'feat') return 'Added';
  if (type === 'fix') return 'Fixed';
  return 'Changed'; // docs, chore, refactor, style, perf, test, build, ci, revert
}

function parseSubject(subject) {
  const match = subject.match(/^(\w+)(?:\(([^)]+)\))?!?:\s*(.+)$/);
  if (!match || !CONVENTIONAL_TYPES.has(match[1].toLowerCase())) {
    return { section: 'Changed', scope: null, text: subject };
  }
  const [, type, scope, text] = match;
  return { section: typeToSection(type), scope: scope ?? null, text };
}

function loadState() {
  if (!existsSync(STATE_PATH)) return { lastSha: null };
  return JSON.parse(readFileSync(STATE_PATH, 'utf8'));
}

function saveState(state) {
  writeFileSync(STATE_PATH, JSON.stringify(state, null, 2) + '\n');
}

function getCommits(sinceSha) {
  const range = sinceSha ? `${sinceSha}..HEAD` : 'HEAD';
  const raw = execSync(
    `git log ${range} --no-merges --date=short --pretty=format:'%H%x1f%ad%x1f%s'`,
    { cwd: ROOT, encoding: 'utf8', maxBuffer: 1024 * 1024 * 32 },
  ).trim();
  if (!raw) return [];
  return raw
    .split('\n')
    .map((line) => {
      const [sha, date, subject] = line.split('\x1f');
      return { sha, date, subject };
    })
    .reverse(); // oldest first, so date groups build up chronologically within a day
}

function groupByDate(commits) {
  const byDate = new Map();
  for (const commit of commits) {
    if (!byDate.has(commit.date)) {
      byDate.set(commit.date, { Added: [], Changed: [], Fixed: [] });
    }
    const { section, scope, text } = parseSubject(commit.subject);
    const bucket = byDate.get(commit.date);
    const entry = scope ? `**${scope}**: ${text}` : text;
    if (!bucket[section].includes(entry)) bucket[section].push(entry);
  }
  // newest date first
  return [...byDate.entries()].sort((a, b) => (a[0] < b[0] ? 1 : -1));
}

function renderMarkdown(dateGroups) {
  const lines = [];
  for (const [date, sections] of dateGroups) {
    lines.push(`## ${date}`, '');
    for (const section of SECTION_ORDER) {
      if (sections[section].length === 0) continue;
      lines.push(`### ${section}`);
      for (const item of sections[section]) lines.push(`- ${item}`);
      lines.push('');
    }
  }
  return lines.join('\n').trimEnd() + '\n';
}

function renderTs(dateGroups) {
  const entries = dateGroups.map(([date, sections]) => ({
    date,
    added: sections.Added,
    changed: sections.Changed,
    fixed: sections.Fixed,
  }));
  const body = JSON.stringify(entries, null, 2);
  return `import type { ChangelogEntry } from '../types/api';\n\n// Generated by scripts/generate-changelog.mjs from git history - do not hand-edit\n// individual entries, re-run the script instead.\nexport const changelog: ChangelogEntry[] = ${body};\n`;
}

function main() {
  const state = loadState();
  const commits = getCommits(state.lastSha);

  if (commits.length === 0) {
    console.log('No new commits since last generation.');
    return;
  }

  const dateGroups = groupByDate(commits);
  const newMarkdown = renderMarkdown(dateGroups);

  const existingMarkdown = existsSync(CHANGELOG_MD_PATH)
    ? readFileSync(CHANGELOG_MD_PATH, 'utf8').replace(/^# Changelog\n\nAll notable changes to OrderMate are documented here\.\n\n/, '')
    : '';

  const header = '# Changelog\n\nAll notable changes to OrderMate are documented here.\n\n';
  const fullMarkdown = header + newMarkdown + (existingMarkdown ? '\n' + existingMarkdown : '');
  writeFileSync(CHANGELOG_MD_PATH, fullMarkdown);

  // For the TS data file, always regenerate from the full merged history so
  // the docs page reflects everything, not just this run's delta.
  const allDateGroups = parseFullMarkdownBackToGroups(fullMarkdown);
  writeFileSync(CHANGELOG_TS_PATH, renderTs(allDateGroups));

  const lastSha = commits[commits.length - 1].sha;
  saveState({ lastSha });

  console.log(`Processed ${commits.length} commit(s) across ${dateGroups.length} date group(s).`);
  console.log(`Updated ${path.relative(ROOT, CHANGELOG_MD_PATH)} and ${path.relative(ROOT, CHANGELOG_TS_PATH)}.`);
}

// Re-parses the merged CHANGELOG.md content back into date groups so the TS
// data file always mirrors the full markdown file, including entries from
// prior runs that this run didn't touch.
function parseFullMarkdownBackToGroups(markdown) {
  const groups = [];
  let current = null;
  let currentSection = null;
  for (const line of markdown.split('\n')) {
    const dateMatch = line.match(/^## (\d{4}-\d{2}-\d{2})$/);
    if (dateMatch) {
      current = [dateMatch[1], { Added: [], Changed: [], Fixed: [] }];
      groups.push(current);
      currentSection = null;
      continue;
    }
    const sectionMatch = line.match(/^### (Added|Changed|Fixed)$/);
    if (sectionMatch) {
      currentSection = sectionMatch[1];
      continue;
    }
    const itemMatch = line.match(/^- (.+)$/);
    if (itemMatch && current && currentSection) {
      current[1][currentSection].push(itemMatch[1]);
    }
  }
  return groups;
}

main();
